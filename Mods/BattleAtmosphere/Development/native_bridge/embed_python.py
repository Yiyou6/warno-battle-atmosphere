"""Build deterministic embedded Python source; never run its game-dependent code here."""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[4]
source = root / 'Mods/BAScriptProbe/AutoRuntimeRoot/CommonData/Python/Eugen'
target = Path(__file__).with_name('embedded_python.h')
names = ['ba_allocator', 'ba_front', 'ba_transport', 'ba_tactics', 'ba_space', 'ba_autorun', 'ba_fixture']
lines = ['/* Generated by embed_python.py; UTF-8 Python 2.5 source. */']
manifest = {}
present = []
for name in names:
    path = (source if name == 'ba_fixture' else root / 'Mods/BattleAtmosphere/Runtime/Python') / (name + '.py')
    if not path.exists():
        continue
    data = path.read_bytes().replace(b'\r\n', b'\n')
    manifest[name] = hashlib.sha256(data).hexdigest()
    present.append(name)
    lines.append('static const char embedded_' + name + '[] =')
    for line in data.splitlines(keepends=True):
        lines.append('"' + ''.join('\\%03o' % b for b in line) + '"')
    lines.append(';')
lines.append('static const struct { const char *name, *source; } embedded_modules[] = {')
for name in present:
    lines.append('{"%s", embedded_%s},' % (name, name))
lines.append('{NULL,NULL}};')
target.write_text('\n'.join(lines) + '\n', encoding='ascii')
target.with_suffix('.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(manifest)
