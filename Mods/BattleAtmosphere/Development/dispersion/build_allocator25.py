"""Generate the same allocation core for WARNO's Python 2.5 interpreter.

This is a syntax/record compatibility transform, not a new planning algorithm.
Generated output remains a research module until a full battle adapter exists.
"""
import ast
from pathlib import Path


class Compat(ast.NodeTransformer):
    def visit_ImportFrom(self, node):
        if node.module == 'dataclasses':
            return None
        if node.module == 'math':
            node.names = [n for n in node.names if n.name != 'isfinite']
        return node

    def visit_ClassDef(self, node):
        fields = [n for n in node.body if isinstance(n, ast.AnnAssign)]
        if fields:
            params, assignments = [], []
            for f in fields:
                name = f.target.id
                if isinstance(f.value, ast.Call) and isinstance(f.value.func, ast.Name) and f.value.func.id == 'field':
                    assignments.append('self.%s = False' % name)
                    continue
                params.append(name + ('=' + ast.unparse(f.value) if f.value else ''))
                assignments.append('self.%s = %s' % (name, name))
            init = ast.parse('def __init__(self, ' + ', '.join(params) + '):\n' +
                             '\n'.join('    ' + a for a in assignments)).body[0]
            node.body = [init] + [n for n in node.body if not isinstance(n, ast.AnnAssign)]
            node.decorator_list = []
        node.bases = node.bases or [ast.Name(id='object', ctx=ast.Load())]
        return self.generic_visit(node)

    def visit_FunctionDef(self, node):
        args = node.args
        if args.kwonlyargs:
            args.args += args.kwonlyargs
            args.defaults += [d for d in args.kw_defaults if d is not None]
            args.kwonlyargs, args.kw_defaults = [], []
        return self.generic_visit(node)

    def visit_DictComp(self, node):
        self.generic_visit(node)
        return ast.Call(func=ast.Name(id='dict', ctx=ast.Load()), args=[
            ast.GeneratorExp(elt=ast.Tuple(elts=[node.key, node.value], ctx=ast.Load()),
                             generators=node.generators)], keywords=[])

    def visit_SetComp(self, node):
        self.generic_visit(node)
        return ast.Call(func=ast.Name(id='set', ctx=ast.Load()), args=[
            ast.GeneratorExp(elt=node.elt, generators=node.generators)], keywords=[])

    def visit_Set(self, node):
        return ast.Call(func=ast.Name(id='set', ctx=ast.Load()),
                        args=[ast.List(elts=[self.visit(x) for x in node.elts], ctx=ast.Load())], keywords=[])

    def visit_List(self, node):
        if not any(isinstance(x, ast.Starred) for x in node.elts):
            return self.generic_visit(node)
        pieces = [ast.Call(func=ast.Name(id='list', ctx=ast.Load()), args=[self.visit(x.value)], keywords=[])
                  if isinstance(x, ast.Starred) else ast.List(elts=[self.visit(x)], ctx=ast.Load())
                  for x in node.elts]
        result = pieces[0]
        for piece in pieces[1:]:
            result = ast.BinOp(left=result, op=ast.Add(), right=piece)
        return result


PRELUDE = '''# Generated by build_allocator25.py; do not hand edit.
from __future__ import division
def isfinite(value):
    return value == value and abs(value) != float('inf')
class StableDict(dict):
    def __iter__(self):
        return iter(sorted(dict.keys(self)))
    def values(self):
        return [self[k] for k in self]
    def items(self):
        return [(k, self[k]) for k in self]
'''


def build():
    directory = Path(__file__).resolve().parent
    source = (directory / 'allocator.py').read_text(encoding='utf-8')
    source = source.replace('max(edges.values(), default=0)', 'max(list(edges.values()) or [0])')
    source = source.replace('return dict(sorted(output.items()))', 'return StableDict(output)')
    source = source.replace('return round(1000 * (2 * rank + 1) / weight)',
                            'return int(round(1000 * (2 * rank + 1) / weight))')
    tree = ast.fix_missing_locations(Compat().visit(ast.parse(source)))
    generated = PRELUDE + ast.unparse(tree) + '\n'
    (directory / 'allocator25.py').write_text(generated, encoding='utf-8')
    return generated


if __name__ == '__main__':
    build()
